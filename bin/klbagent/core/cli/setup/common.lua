local function _is_windows()
	return package.config:sub(1, 1) == "\\"
end


M.is_windows = _is_windows


local function _sh_quote(s)
	s = tostring(s)
	if _is_windows() then
		return '"' .. string.gsub(s, '"', '\\"') .. '"'
	end

	return "'" .. string.gsub(s, "'", "'\\''") .. "'"
end


M.sh_quote = _sh_quote


-- @brief 执行 shell 命令并捕获 stdout+stderr
-- @param [in] cmd[string]
-- @return ok[boolean]
-- @return out[string]
-- @return rc[number]
local function _run(cmd)
	local tmp = os.tmpname()
	local ok_ex, what, code = os.execute(cmd .. " > " .. _sh_quote(tmp) .. " 2>&1")

	local out = ""
	local f = io.open(tmp, "rb")
	if f ~= nil then
		out = f:read("*a") or ""
		f:close()
	end

	os.remove(tmp)

	local rc = 0
	if ok_ex == true or ok_ex == 0 then
		rc = 0
	elseif what == "exit" and type(code) == "number" then
		rc = code
	else
		rc = 1
	end

	return (0 == rc), out, rc
end


M.run = _run


-- sudo NOPASSWD 探测结果 (只探测一次)
local g_sudo_ok = nil


local function _sudo_nopasswd()
	if _is_windows() then
		return false
	end

	if g_sudo_ok == nil then
		local ok = _run("sudo -n true")
		g_sudo_ok = ok and true or false
	end

	return g_sudo_ok
end


-- sudo 口令 (进程内缓存; 不落盘 M4)
local g_sudo_pass = nil


-- @brief 交互式读 sudo 口令 (/dev/tty; 仅一次)
-- @note 无控制终端 / ALUA_SUDO_PROMPT=0 → 跳过, 避免读走 stdin 管道
-- @return pass[string|nil]
local function _read_tty_pass()
	if os.getenv("ALUA_SUDO_PROMPT") == "0" then
		return nil
	end

	local tty = io.open("/dev/tty", "r")
	if tty == nil then
		return nil
	end

	io.stderr:write("sudo password (once, not stored): ")
	io.stderr:flush()
	os.execute("stty -echo < /dev/tty 2>/dev/null")
	local pass = tty:read("*l")
	os.execute("stty echo < /dev/tty 2>/dev/null")
	tty:close()
	io.stderr:write("\n")

	if type(pass) ~= "string" or pass == "" then
		return nil
	end

	return pass
end


-- @brief 需 root 的命令 (system scope unit / init.d)
-- @note 顺序: NOPASSWD → ALUA_DEPLOY_SUDO → tty 交互口令 → 失败
-- @param [in] cmd[string]
-- @return ok[boolean]
-- @return out[string]
-- @return rc[number]
M.sudo = function (cmd)
	if _is_windows() then
		return _run(cmd)
	end

	if _sudo_nopasswd() then
		return _run("sudo -n " .. cmd)
	end

	if g_sudo_pass == nil then
		local env = os.getenv("ALUA_DEPLOY_SUDO")
		if type(env) == "string" and env ~= "" then
			g_sudo_pass = env
		else
			g_sudo_pass = _read_tty_pass() or ""
		end
	end

	if g_sudo_pass ~= "" then
		local ok, out, rc = _run("printf '%s\\n' " .. _sh_quote(g_sudo_pass) .. " | sudo -S " .. cmd)
		if not ok then
			-- 口令失效: 清缓存, 下次可重新提示
			g_sudo_pass = nil
		end

		return ok, out, rc
	end

	return false, "sudo: need NOPASSWD target, ALUA_DEPLOY_SUDO, or an interactive tty", 1
end


-- @brief 本进程 alua 可执行文件绝对路径
-- @note 不可用 io.popen("readlink -f /proc/self/exe"): 子进程 self 指向 readlink 自身
-- @return path[string]
M.alua_bin = function ()
	if _is_windows() then
		local la = os.getenv("LOCALAPPDATA")
		if type(la) == "string" and la ~= "" then
			local p = la .. "\\Programs\\klua\\alua.exe"
			local f = io.open(p, "rb")
			if f ~= nil then
				f:close()
				return p
			end
		end

		return "alua.exe"
	end

	local ok_l, lfs = pcall(require, "lfs")
	if ok_l and type(lfs) == "table" and type(lfs.symlinkattributes) == "function" then
		local ok_a, attr = pcall(lfs.symlinkattributes, "/proc/self/exe", "target")
		if ok_a and type(attr) == "table" and type(attr.target) == "string" and attr.target ~= "" then
			return attr.target
		end
	end

	return "/usr/local/bin/alua"
end


local function _host()
	local ok, hi = pcall(hostinfo.probe)
	if ok and type(hi) == "table" then
		return hi
	end

	return {}
end


M.host_kind = function ()
	return tostring(_host().host_kind or "unknown")
end


M.has_systemctl = function ()
	local hi = _host()
	return type(hi.caps) == "table" and hi.caps.systemctl == true
end


-- @brief pref 配置目录 (无尾斜杠)
-- @return dir[string]
M.pref_dir = function ()
	local dir = config.dir()
	if type(dir) ~= "string" then
		return ""
	end

	return string.gsub(dir, "[/\\]+$", "")
end


local function _file_exists(path)
	if type(path) ~= "string" or path == "" then
		return false
	end

	local f = io.open(path, "rb")
	if f == nil then
		return false
	end

	f:close()
	return true
end


M.file_exists = _file_exists


-- @brief 经 sudo 写系统文件 (tmp + cp + chmod)
-- @param [in] path[string]
-- @param [in] content[string]
-- @param [in] mode[string]			权限位, 如 "644"/"755"
-- @return ok[boolean]
-- @return err[string|nil]
local function _write_file_elevated(path, content, mode)
	local tmp = os.tmpname()
	local f = io.open(tmp, "wb")
	if f == nil then
		return false, "temp file fail"
	end

	f:write(content)
	f:close()

	local ok, out = M.sudo("cp " .. _sh_quote(tmp) .. " " .. _sh_quote(path)
		.. " && chmod " .. mode .. " " .. _sh_quote(path))
	os.remove(tmp)
	if not ok then
		return false, "write file fail: " .. tostring(out or "")
	end

	return true, nil
end


-- @brief 单元文件路径
-- @param [in] name[string]
-- @param [in] scope[string]			"system"|"user"
-- @return path[string]
M.unit_path = function (name, scope)
	if scope == "system" then
		return "/etc/systemd/system/" .. name
	end

	local home = os.getenv("HOME")
	if type(home) ~= "string" or home == "" then
		return ""
	end

	return home .. "/.config/systemd/user/" .. name
end


-- @brief systemctl 查询 (只读; 不升权)
local function _systemctl_raw(scope, args)
	local cmd = "systemctl "
	if scope == "user" then
		cmd = "systemctl --user "
	end

	return _run(cmd .. args)
end


-- @brief systemctl 变更 (system scope 经 sudo; user scope 直跑)
M.systemctl = function (scope, args)
	if scope == "system" then
		return M.sudo("systemctl " .. args)
	end

	return _systemctl_raw(scope, args)
end


local function _query(scope, args)
	local _, out = _systemctl_raw(scope, args)
	return string.match(tostring(out or ""), "^%s*(.-)%s*$") or ""
end


-- @brief 在输出中按行精确匹配状态词
-- @note _run 合并 stderr (可能有 libselinux 等噪声行), 故不能整串比较
-- @param [in] out[string]
-- @param [in] words[table]			候选状态词
-- @return word[string]			命中词; 无命中 ""
local function _status_word(out, words)
	local set = {}
	for i = 1, #words do
		set[words[i]] = true
	end

	for line in string.gmatch(tostring(out or ""), "[^\r\n]+") do
		local v = string.match(line, "^%s*(.-)%s*$")
		if set[v] then
			return v
		end
	end

	return ""
end


local _ENABLED = { "enabled", "enabled-runtime" }
local _ACTIVE = { "active", "activating", "reloading", "deactivating" }
local _STATE = { "active", "inactive", "failed", "activating", "deactivating", "reloading" }


local function _is_enabled(scope, name)
	local w = _status_word(_query(scope, "is-enabled " .. name), _ENABLED)
	return w ~= ""
end


-- @brief 单元 scope: 活动 > 已启用 > 已安装(user 优先); nil=未安装 / 无 systemd
-- @note disabled/masked 不算"已启用"; 仅安装未启用时 user 优先 (本工具生成的单元在 user)
-- @param [in] name[string]
-- @return scope[string|nil]
M.unit_scope = function (name)
	if not M.has_systemctl() then
		return nil
	end

	if _status_word(_query("system", "is-active " .. name), _ACTIVE) == "active" then
		return "system"
	end

	if _status_word(_query("user", "is-active " .. name), _ACTIVE) == "active" then
		return "user"
	end

	if _is_enabled("system", name) then
		return "system"
	end

	if _is_enabled("user", name) then
		return "user"
	end

	if _file_exists(M.unit_path(name, "user")) then
		return "user"
	end

	if _file_exists(M.unit_path(name, "system")) then
		return "system"
	end

	return nil
end


-- @brief 读单元文件 (常见 644 直读; 失败再经 sudo cat)
M.read_unit = function (path, scope)
	local f = io.open(path, "rb")
	if f ~= nil then
		local data = f:read("*a") or ""
		f:close()
		if data ~= "" then
			return data, nil
		end
	end

	if scope == "system" then
		local ok, out = M.sudo("cat " .. _sh_quote(path))
		if ok and type(out) == "string" and out ~= "" then
			return out, nil
		end

		return nil, "read unit fail: " .. tostring(out or "")
	end

	return nil, "read unit fail: " .. tostring(path)
end


-- @brief 写单元文件 (user 直写; system 经 sudo cp)
M.write_unit = function (path, content, scope)
	if scope == "user" then
		local dir = string.match(path, "^(.*)[/\\][^/\\]+$")
		if type(dir) == "string" and dir ~= "" then
			os.execute("mkdir -p " .. _sh_quote(dir))
		end

		local f = io.open(path, "wb")
		if f == nil then
			return false, "write unit fail: " .. path
		end

		f:write(content)
		f:close()
		return true, nil
	end

	local ok, err = _write_file_elevated(path, content, "644")
	if not ok then
		return false, "write unit fail: " .. tostring(err or path)
	end

	return true, nil
end


-- @brief 取 ExecStart 行值 (含二进制与参数)
M.exec_start = function (content)
	for line in string.gmatch(content or "", "[^\r\n]+") do
		local v = string.match(line, "^%s*ExecStart%s*=%s*(.-)%s*$")
		if type(v) == "string" and v ~= "" then
			return v
		end
	end

	return nil
end


-- @brief 替换 ExecStart 行 (无则挂到 [Service] 之后)
M.set_exec_start = function (content, exec)
	local out, n = string.gsub(content or "", "[^\r\n]*ExecStart[^\r\n]*", "ExecStart=" .. exec, 1)
	if 0 < n then
		return out
	end

	local a, b = string.find(out, "%[Service%][^\r\n]*")
	if a == nil then
		return out .. "\n[Service]\nExecStart=" .. exec .. "\n"
	end

	return string.sub(out, 1, b) .. "\nExecStart=" .. exec .. string.sub(out, b + 1)
end


-- @brief ExecStart 首个 token (二进制; 去引号)
M.exec_bin = function (exec)
	local s = string.match(exec or "", "^%s*(.-)%s*$")
	if type(s) ~= "string" or s == "" then
		return nil
	end

	local q = string.match(s, '^"([^"]+)"')
	if q ~= nil then
		return q
	end

	return string.match(s, "^%S+")
end


-- @brief 二进制路径含空格时补引号 (ExecStart 用)
M.quote_exec_bin = function (bin)
	bin = tostring(bin or "")
	if string.find(bin, " ", 1, true) ~= nil then
		return '"' .. bin .. '"'
	end

	return bin
end


-- @brief 从 ExecStart 取 serve 的 port / profile
-- @return port[number|nil]
-- @return profile[string|nil]
M.exec_serve_opts = function (exec)
	local port = nil
	local profile = nil

	for tok in string.gmatch(exec or "", "%S+") do
		local n = tonumber(tok)
		if type(n) == "number" and string.match(tok, "^%d+$") then
			port = n
		elseif tok == "readonly" or tok == "net" or tok == "device" or tok == "unsafe" then
			profile = tok
		end
	end

	return port, profile
end


-- @brief 单元活动状态 (active|inactive|failed|activating|unknown)
M.unit_state = function (name, scope)
	local w = _status_word(_query(scope, "is-active " .. name), _STATE)
	if w ~= "" then
		return w
	end

	return "unknown"
end


-- ==== SysV init.d (嵌入式; 无 systemd) ====

-- @brief /etc/init.d 目录是否存在 (仅探测, 不判 systemd)
-- @return yes[boolean]
M.has_initd = function ()
	if _is_windows() then
		return false
	end

	local ok_l, lfs = pcall(require, "lfs")
	if ok_l and type(lfs) == "table" and type(lfs.attributes) == "function" then
		local mode = lfs.attributes(M.INITD_DIR, "mode")
		return mode == "directory"
	end

	return _run("test -d " .. _sh_quote(M.INITD_DIR))
end


-- @brief 判断 init.d 脚本是否由 alua setup 生成 (M7; 防误停/误改外来脚本)
-- @param [in] content[string|nil]
-- @return owned[boolean]
M.initd_owned = function (content)
	if type(content) ~= "string" then
		return false
	end

	return string.find(content, M.INITD_MARK, 1, true) ~= nil
end


-- @brief init.d 脚本路径
-- @return path[string]
M.initd_path = function ()
	return string.gsub(M.INITD_DIR, "[/\\]+$", "") .. "/" .. M.INITD_NAME
end


-- @brief 读 init.d 脚本 (直读; 失败经 sudo cat)
-- @return content[string|nil]
-- @return err[string|nil]
M.read_initd = function (path)
	local f = io.open(path, "rb")
	if f ~= nil then
		local data = f:read("*a") or ""
		f:close()
		if data ~= "" then
			return data, nil
		end
	end

	local ok, out = M.sudo("cat " .. _sh_quote(path))
	if ok and type(out) == "string" and out ~= "" then
		return out, nil
	end

	return nil, nil
end


-- @brief 写 init.d 脚本 (直写; 失败经 sudo cp)
-- @return ok[boolean]
-- @return err[string|nil]
M.write_initd = function (path, content)
	local f = io.open(path, "wb")
	if f ~= nil then
		f:write(content)
		f:close()
		return true, nil
	end

	local dir = string.match(path, "^(.*)[/\\][^/\\]+$")
	if type(dir) == "string" and dir ~= "" then
		os.execute("mkdir -p " .. _sh_quote(dir) .. " 2>/dev/null")
		f = io.open(path, "wb")
		if f ~= nil then
			f:write(content)
			f:close()
			return true, nil
		end
	end

	local ok, err = _write_file_elevated(path, content, "755")
	if not ok then
		return false, err or ("write initd fail: " .. path)
	end

	return true, nil
end


-- @brief 执行位置位/复位 (rcS 只跑可执行 SXX*)
-- @param [in] path[string]
-- @param [in] on[boolean]
-- @return ok[boolean]
-- @return err[string|nil]
M.chmod_exec = function (path, on)
	local flag = "+x"
	if not on then
		flag = "-x"
	end

	local ok, out, rc = _run("chmod " .. flag .. " " .. _sh_quote(path))
	if ok then
		return true, nil
	end

	local ok_s, out_s = M.sudo("chmod " .. flag .. " " .. _sh_quote(path))
	if not ok_s then
		return false, "chmod fail: " .. tostring(out_s or out or rc)
	end

	return true, nil
end


-- @brief init.d 脚本内 ALUA_ARGS 值
-- @param [in] content[string]
-- @return args[string|nil]
M.initd_args = function (content)
	local v = string.match(content or "", 'ALUA_ARGS="([^"]*)"')
	if type(v) ~= "string" or v == "" then
		return nil
	end

	return string.match(v, "^%s*(.-)%s*$")
end


-- @brief 改写 init.d 脚本内 ALUA_ARGS 值
-- @param [in] content[string]
-- @param [in] args[string]
-- @return content[string]
M.set_initd_args = function (content, args)
	local out, n = string.gsub(content or "", '(ALUA_ARGS=")[^"]*"', "%1" .. args .. '"', 1)
	if 0 < n then
		return out
	end

	return content
end


-- @brief 执行 init.d 脚本动作 (失败经 sudo 重试)
-- @param [in] path[string]
-- @param [in] action[string]			start|stop|restart|status
-- @return ok[boolean]
-- @return out[string]
M.run_initd = function (path, action)
	local cmd = "sh " .. _sh_quote(path) .. " " .. action
	local ok, out, rc = _run(cmd)
	if ok then
		return true, out
	end

	local ok_s, out_s = M.sudo(cmd)
	if ok_s then
		return true, out_s
	end

	return false, tostring(out_s or out or rc)
end


-- @brief init.d 服务是否在跑 (status 子命令 rc=0)
-- @param [in] path[string]
-- @return running[boolean]
M.initd_running = function (path)
	local ok = _run("sh " .. _sh_quote(path) .. " status")
	return ok
end


