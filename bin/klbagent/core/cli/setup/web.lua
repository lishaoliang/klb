-- @brief 解析 yes|no 与选项 (--listen 可重复)
-- @param [in] argv[table]
-- @return opt[table]
local function _parse(argv)
	local opt = {
		action = nil,
		listen = {},
		addr = nil,
		cert = nil,
		key = nil,
		allow = {},
		deny = {},
		acl_default = nil,
	}

	local i = 1
	while i <= #argv do
		local a = argv[i]
		if a == "yes" or a == "no" then
			opt.action = a
			i = i + 1
		elseif a == "--listen" or a == "-l" then
			if type(argv[i + 1]) == "string" and argv[i + 1] ~= "" then
				opt.listen[#opt.listen + 1] = argv[i + 1]
			end

			i = i + 2
		elseif a == "--addr" then
			opt.addr = argv[i + 1]
			i = i + 2
		elseif a == "--cert" then
			opt.cert = argv[i + 1]
			i = i + 2
		elseif a == "--key" then
			opt.key = argv[i + 1]
			i = i + 2
		elseif a == "--allow" or a == "--deny" then
			local v = argv[i + 1]
			if type(v) == "string" and v ~= "" then
				local key = (a == "--allow") and "allow" or "deny"
				opt[key][#opt[key] + 1] = v
			end

			i = i + 2
		elseif a == "--acl-default" then
			opt.acl_default = argv[i + 1]
			i = i + 2
		else
			i = i + 1
		end
	end

	return opt
end


-- @brief 解析 PORT:PROTO 端口项
-- @param [in] text[string]
-- @return item[table|nil]
-- @return err[string|nil]
local function _parse_listen(text)
	local port_s = text
	local proto = "http+https"

	local sep = string.find(text, ":", 1, true)
	if sep ~= nil then
		port_s = string.sub(text, 1, sep - 1)
		proto = string.sub(text, sep + 1)
	end

	if string.lower(proto) == "" then
		proto = "http+https"
	end

	local port = tonumber(port_s)
	if port == nil then
		return nil, "bad --listen port: " .. tostring(text)
	end

	port = math.floor(port)
	if port < 1 or 65535 < port then
		return nil, "bad --listen port: " .. tostring(text)
	end

	local item = config.web.item(port, proto, "", "")
	if item == nil then
		return nil, "bad --listen proto: " .. tostring(text)
	end

	return item, nil
end


-- @brief web.json 路径 (单元/@ 参数)
-- @return path[string]
local function _cfg_path()
	local pref = common.pref_dir()
	if pref == "" then
		return ""
	end

	return pref .. "/web.json"
end


-- @brief 是否本机回环监听地址 (缺省 127.0.0.1)
-- @param [in] addr[string|nil]
-- @return yes[boolean]
local function _is_loopback(addr)
	if type(addr) ~= "string" or addr == "" then
		return true
	end

	local low = string.lower(addr)
	if low == "localhost" or low == "::1" or low == "[::1]" then
		return true
	end

	return string.match(low, "^127%.") ~= nil
end


-- @brief 按 CLI 选项改写 web.json (未给选项则仅确保存在)
-- @param [in] opt[table]
-- @param [in,out] result[table]
-- @return ok[boolean]
-- @return err[string|nil]
local function _apply_cfg(opt, result)
	local cfg = config.web.load()
	cfg = config.web.normalize(cfg)

	local changed = false

	if #opt.listen > 0 then
		local listen = {}
		for i = 1, #opt.listen do
			local item, err = _parse_listen(opt.listen[i])
			if item == nil then
				return false, err
			end

			if type(opt.cert) == "string" and opt.cert ~= "" then
				item.cert = opt.cert
			end

			if type(opt.key) == "string" and opt.key ~= "" then
				item.key = opt.key
			end

			listen[#listen + 1] = item
		end

		cfg.listen = listen
		changed = true
	elseif type(opt.cert) == "string" and opt.cert ~= "" then
		for i = 1, #cfg.listen do
			if cfg.listen[i].tls then
				cfg.listen[i].cert = opt.cert
			end
		end

		changed = true
	end

	if type(opt.key) == "string" and opt.key ~= "" then
		for i = 1, #cfg.listen do
			if cfg.listen[i].tls then
				cfg.listen[i].key = opt.key
			end
		end

		changed = true
	end

	if type(opt.addr) == "string" and opt.addr ~= "" then
		cfg.addr = opt.addr
		changed = true
	end

	-- 黑白名单: 显式给出才替换对应列表; 规则非法即报错 (不静默丢弃)
	for _, key in ipairs({ "allow", "deny" }) do
		local list = opt[key]
		if 0 < #list then
			for i = 1, #list do
				if not web_acl.rule_ok(list[i]) then
					return false, "bad --" .. key .. " rule: " .. tostring(list[i])
				end
			end

			cfg.acl[key] = list
			changed = true
		end
	end

	if type(opt.acl_default) == "string" and opt.acl_default ~= "" then
		local d = string.lower(opt.acl_default)
		if d ~= "allow" and d ~= "deny" then
			return false, "bad --acl-default: " .. opt.acl_default
		end

		cfg.acl.default = d
		changed = true
	end

	-- 非回环监听禁止明文 http (避免配置页/口令在局域网明文传输; http+https 亦含明文面)
	local addr = cfg.addr
	if not _is_loopback(addr) then
		for i = 1, #cfg.listen do
			local item = cfg.listen[i]
			if type(item) == "table" and item.plain == true then
				return false, "plain http not allowed on non-loopback addr; use --listen PORT:https"
			end
		end
	end

	if changed then
		if not config.web.save(cfg) then
			return false, "save web.json fail"
		end

		result.changed = true
	end

	cfg = config.web.load()
	result.addr = cfg.addr
	result.listens = cfg.listen
	result.acl = cfg.acl
	return true, nil
end


-- @brief 从 pref 反推 HOME (pref 形如 <home>/.local/share/klua/alua)
-- @param [in] pref[string]
-- @return home[string]			推不出时为空串
local function _pref_home(pref)
	local home = string.match(pref, "^(.-)/%.local/share/klua/alua$")
	if type(home) == "string" and home ~= "" then
		return home
	end

	return ""
end


-- @brief 生成 web 的 user 单元
-- @param [in] bin[string]
-- @param [in] cfg_path[string]
-- @return text[string]
local function _unit_text(bin, cfg_path)
	local pref = common.pref_dir()
	local home = os.getenv("HOME") or ""

	local lines = {
		"[Unit]",
		"Description=alua web config page (klbweb; /api/v1/*)",
		"After=network-online.target",
		"Wants=network-online.target",
		"",
		"[Service]",
		"Type=simple",
		"ExecStart=" .. common.quote_exec_bin(bin) .. " pkg run alua_web serve @" .. cfg_path,
		"EnvironmentFile=-" .. pref .. "/serve.env",
		"Environment=HOME=" .. home,
		"Restart=on-failure",
		"RestartSec=3",
		"TimeoutStopSec=5",
		"",
		"[Install]",
		"WantedBy=default.target",
		"",
	}

	return table.concat(lines, "\n")
end


-- @brief 单元已存在时按当前生成结果校准 (含 ExecStart / 停止策略)
-- @param [in] path[string]
-- @param [in] scope[string]
-- @return changed[boolean]
-- @return err[string|nil]
local function _sync_unit(path, scope)
	local content, err_c = common.read_unit(path, scope)
	if content == nil then
		return false, err_c
	end

	local bin = common.exec_bin(common.exec_start(content)) or common.alua_bin()
	local want = _unit_text(bin, _cfg_path())
	if content == want then
		return false, nil
	end

	local ok_w, err_w = common.write_unit(path, want, scope)
	if not ok_w then
		return false, err_w
	end

	return true, nil
end


-- @brief linux 分支: systemd system|user
-- @param [in] opt[table]
-- @param [in,out] result[table]
-- @return ok[boolean]
-- @return err[string|nil]
local function _linux(opt, result)
	local unit = common.WEB_UNIT
	local scope = common.unit_scope(unit)
	result.scope = scope

	local ok_c, err_c = _apply_cfg(opt, result)
	if not ok_c then
		return false, err_c
	end

	if scope == nil then
		if opt.action == "no" then
			result.message = "alua web unit not installed; nothing to disable"
			return true, nil
		end

		local cfg_path = _cfg_path()
		if cfg_path == "" then
			return false, "pref dir unavailable"
		end

		scope = "user"
		result.scope = scope
		local path = common.unit_path(unit, scope)
		local ok_w, err_w = common.write_unit(path, _unit_text(common.alua_bin(), cfg_path), scope)
		if not ok_w then
			return false, err_w
		end

		local ok_r, err_r = common.daemon_reload(scope)
		if not ok_r then
			return false, err_r
		end

		result.changed = true
	else
		local path = common.unit_path(unit, scope)
		local changed, err_s = _sync_unit(path, scope)
		if err_s ~= nil then
			return false, err_s
		end

		if changed then
			result.changed = true
			local ok_r, err_r = common.daemon_reload(scope)
			if not ok_r then
				return false, err_r
			end
		end
	end

	if opt.action == "no" then
		local ok_d, err_d = common.disable_unit(unit, scope)
		if not ok_d then
			return false, err_d
		end

		-- 停止走默认 SIGTERM (C 层 signal 转 env is_exit, 主循环收尾退出);
		-- 兼容旧 SIGKILL 单元: 清 failed 残留为 inactive(dead)
		common.systemctl(scope, "reset-failed " .. unit)

		result.changed = true
		result.message = "alua web disabled"
		return true, nil
	end

	local state = common.unit_state(unit, scope)
	local ok_e, err_e = common.enable_unit(unit, scope)
	if not ok_e then
		return false, err_e
	end

	if result.changed or state ~= "active" then
		local ok_s, err_s = common.restart_unit(unit, scope)
		if not ok_s then
			return false, err_s
		end
	end

	result.message = "alua web enabled"
	return true, nil
end


-- @brief web 的 init.d 脚本路径 (S99_alua_web)
-- @return path[string]
local function _initd_path()
	return string.gsub(common.INITD_DIR, "[/\\]+$", "") .. "/" .. M.INITD_NAME
end


-- @brief 生成 web 的 SysV init.d 脚本 (PID/日志/ENV 均落 pref)
-- @param [in] bin[string]
-- @param [in] cfg_path[string]
-- @return text[string]
local function _initd_text(bin, cfg_path)
	local pref = common.pref_dir()
	local home = _pref_home(pref)

	local lines = {
		"#!/bin/sh",
		M.INITD_MARK,
		"### BEGIN INIT INFO",
		"# Provides:          alua_web",
		"# Required-Start:    $network $remote_fs",
		"# Required-Stop:     $network $remote_fs",
		"# Default-Start:     2 3 4 5",
		"# Default-Stop:      0 1 6",
		"# Short-Description: alua web config page (klbweb)",
		"### END INIT INFO",
		"",
		"DAEMON=" .. common.sh_quote(bin),
		'ALUA_ARGS="pkg run alua_web serve @' .. cfg_path .. '"',
		'PIDFILE="' .. pref .. '/alua-web.pid"',
		'LOGFILE="' .. pref .. '/alua-web.log"',
		'ENVFILE="' .. pref .. '/serve.env"',
		'PIDDIR="' .. pref .. '"',
		"",
		(home ~= "" and ("HOME=" .. common.sh_quote(home)) or ""),
		(home ~= "" and "export HOME" or ""),
		"",
		'[ -f "$ENVFILE" ] && . "$ENVFILE"',
		"",
		"is_running() {",
		'\t[ -f "$PIDFILE" ] || return 1',
		'\tPID=$(cat "$PIDFILE" 2>/dev/null)',
		'\t[ -n "$PID" ] || return 1',
		'\tkill -0 "$PID" 2>/dev/null || return 1',
		'\t[ "$(cat /proc/$PID/comm 2>/dev/null)" = "alua" ] || return 1',
		"}",
		"",
		"do_start() {",
		"\tif is_running; then",
		'\t\techo "alua web already running (pid $PID)"',
		"\t\treturn 0",
		"\tfi",
		'\trm -f "$PIDFILE"',
		'\t[ -d "$PIDDIR" ] || mkdir -p "$PIDDIR"',
		'\tif [ -f "$LOGFILE" ] && [ "$(wc -c < "$LOGFILE")" -gt 1048576 ]; then',
		'\t\tmv -f "$LOGFILE" "$LOGFILE.1" 2>/dev/null',
		"\tfi",
		'\t"$DAEMON" $ALUA_ARGS >> "$LOGFILE" 2>&1 &',
		"\tNEWPID=$!",
		'\techo "$NEWPID" > "$PIDFILE"',
		"\tsleep 1",
		'\tif ! kill -0 "$NEWPID" 2>/dev/null; then',
		'\t\trm -f "$PIDFILE"',
		'\t\techo "alua web failed to start; see $LOGFILE"',
		"\t\treturn 1",
		"\tfi",
		'\techo "alua web started (pid $NEWPID)"',
		"}",
		"",
		"do_stop() {",
		"\tif ! is_running; then",
		'\t\trm -f "$PIDFILE"',
		'\t\techo "alua web not running"',
		"\t\treturn 0",
		"\tfi",
		'\tkill "$PID" 2>/dev/null',
		"\ti=0",
		'\twhile kill -0 "$PID" 2>/dev/null && [ "$i" -lt 30 ]; do',
		"\t\tsleep 1",
		"\t\ti=$((i + 1))",
		"\tdone",
		'\tkill -9 "$PID" 2>/dev/null',
		'\trm -f "$PIDFILE"',
		'\techo "alua web stopped"',
		"}",
		"",
		"do_status() {",
		"\tif is_running; then",
		'\t\techo "alua web running (pid $PID)"',
		"\t\treturn 0",
		"\tfi",
		'\techo "alua web stopped"',
		"\treturn 3",
		"}",
		"",
		'case "$1" in',
		"\tstart) do_start ;;",
		"\tstop) do_stop ;;",
		"\trestart) do_stop; do_start ;;",
		"\tstatus) do_status ;;",
		"\t*) echo \"Usage: $0 {start|stop|restart|status}\"; exit 2 ;;",
		"esac",
		"",
	}

	return table.concat(lines, "\n")
end


-- @brief linux 分支 (无 systemd): SysV init.d S99_alua_web
-- @param [in] opt[table]
-- @param [in,out] result[table]
-- @return ok[boolean]
-- @return err[string|nil]
local function _initd(opt, result)
	local path = _initd_path()
	local content = common.read_initd(path)
	local owned = common.initd_owned(content) or string.find(content or "", M.INITD_MARK, 1, true) ~= nil
	if content ~= nil and not owned then
		return false, "init.d script not alua-managed: " .. path
	end

	local ok_c, err_c = _apply_cfg(opt, result)
	if not ok_c then
		return false, err_c
	end

	if opt.action == "no" then
		if content == nil then
			result.message = "alua web init.d not installed; nothing to disable"
			return true, nil
		end

		local ok_r, out_r = common.run_initd(path, "stop")
		if not ok_r then
			return false, "init.d stop fail: " .. tostring(out_r or "")
		end

		local ok_x, err_x = common.chmod_exec(path, false)
		if not ok_x then
			return false, err_x
		end

		result.changed = true
		result.message = "alua web disabled"
		return true, nil
	end

	local cfg_path = _cfg_path()
	if cfg_path == "" then
		return false, "pref dir unavailable"
	end

	local text = _initd_text(common.alua_bin(), cfg_path)
	if content == nil or text ~= content then
		local ok_w, err_w = common.write_initd(path, text)
		if not ok_w then
			return false, err_w
		end

		local ok_x, err_x = common.chmod_exec(path, true)
		if not ok_x then
			return false, err_x
		end

		result.changed = true
	end

	if common.initd_running(path) then
		local ok_r, out_r = common.run_initd(path, "restart")
		if not ok_r then
			return false, "init.d restart fail: " .. tostring(out_r or "")
		end
	else
		local ok_s, out_s = common.run_initd(path, "start")
		if not ok_s then
			return false, "init.d start fail: " .. tostring(out_s or "")
		end
	end

	result.message = "alua web enabled"
	return true, nil
end


-- @brief win 分支: 计划任务 klua\alua-web
-- @param [in] opt[table]
-- @param [in,out] result[table]
-- @return ok[boolean]
-- @return err[string|nil]
local function _windows(opt, result)
	local task = common.WEB_TASK
	result.task = task

	local ok_c, err_c = _apply_cfg(opt, result)
	if not ok_c then
		return false, err_c
	end

	if opt.action == "no" then
		common.run('schtasks /End /TN "' .. task .. '"')
		local ok_d = common.run('schtasks /Change /TN "' .. task .. '" /DISABLE')
		if not ok_d then
			result.message = "alua web task not installed; nothing to disable"
			return true, nil
		end

		result.changed = true
		result.message = "alua web task disabled"
		return true, nil
	end

	local cfg_path = _cfg_path()
	if cfg_path == "" then
		return false, "pref dir unavailable"
	end

	local tr = '\\"' .. common.alua_bin() .. '\\" pkg run alua_web serve @' .. cfg_path
	local tr_q = '"' .. tr .. '"'
	local ok_q = common.run('schtasks /Query /TN "' .. task .. '"')
	if not ok_q then
		local ok_n, out_n = common.run('schtasks /Create /TN "' .. task .. '" /TR ' .. tr_q
			.. ' /SC ONLOGON /RL LIMITED /F')
		if not ok_n then
			return false, "schtasks create fail: " .. tostring(out_n or "")
		end

		result.changed = true
	else
		local ok_t = common.run('schtasks /Change /TN "' .. task .. '" /TR ' .. tr_q)
		if not ok_t then
			return false, "schtasks change fail"
		end
	end

	local ok_e, out_e = common.run('schtasks /Change /TN "' .. task .. '" /ENABLE')
	if not ok_e then
		return false, "schtasks enable fail: " .. tostring(out_e or "")
	end

	local ok_r, out_r = common.run('schtasks /Run /TN "' .. task .. '"')
	if not ok_r then
		return false, "schtasks run fail: " .. tostring(out_r or "")
	end

	result.message = "alua web task enabled"
	return true, nil
end


-- @brief 端口组人读串 (8080:http+https,8443:https)
-- @param [in] listens[table]
-- @return text[string]
local function _listens_text(listens)
	local out = {}
	if type(listens) ~= "table" then
		return ""
	end

	for i = 1, #listens do
		local item = listens[i]
		local proto = "http"
		if item.tls and item.plain then
			proto = "http+https"
		elseif item.tls then
			proto = "https"
		end

		out[#out + 1] = tostring(item.port) .. ":" .. proto
	end

	return table.concat(out, ",")
end


-- @brief 黑白名单人读串 (allow=... deny=... default=...)
-- @param [in] acl[table]
-- @return text[string]
local function _acl_text(acl)
	if type(acl) ~= "table" then
		return ""
	end

	local parts = {}
	local allow = acl.allow or {}
	local deny = acl.deny or {}
	if 0 < #allow then
		parts[#parts + 1] = "allow=" .. table.concat(allow, ",")
	end

	if 0 < #deny then
		parts[#parts + 1] = "deny=" .. table.concat(deny, ",")
	end

	parts[#parts + 1] = "default=" .. tostring(acl.default)
	return table.concat(parts, " ")
end


local function _print_text(result)
	fmt.print_kv("entry", result.entry)
	fmt.print_kv("action", result.action)
	fmt.print_kv("platform", result.platform)
	fmt.print_kv("service", result.service)
	if result.task ~= nil then
		fmt.print_kv("task", result.task)
	end

	if result.scope ~= nil then
		fmt.print_kv("scope", result.scope)
	end

	if result.addr ~= nil then
		fmt.print_kv("addr", result.addr)
	end

	if result.listens ~= nil then
		fmt.print_kv("listen", _listens_text(result.listens))
	end

	if result.acl ~= nil then
		fmt.print_kv("acl", _acl_text(result.acl))
	end

	if result.changed ~= nil then
		fmt.print_kv("changed", tostring(result.changed))
	end

	fmt.print_kv("message", result.message or "ok")
end


-- @brief setup web: 端口组配置 + 常驻启停
-- @param [in] argv[table]			{ "yes"|"no", "--listen", "PORT:PROTO", "--addr", IP, ... }
-- @param [in] want_json[boolean]
-- @return ok[boolean]
-- @return code[number]
M.run = function (argv, want_json)
	argv = argv or {}
	if fmt.has_help_flag(argv) then
		M.help()
		return true, codes.OK
	end

	local opt = _parse(argv)
	if opt.action == nil then
		if want_json then
			fmt.print_json(codes.make_error(codes.cli.BAD_REQUEST, "alua setup web yes|no"))
		else
			M.help()
			io.stderr:write("alua setup web: need yes|no\n")
		end

		return false, codes.cli.BAD_REQUEST
	end

	local result = {
		command = "setup",
		schema = common.SCHEMA,
		entry = "web",
		action = opt.action,
		platform = nil,
		service = common.WEB_UNIT,
	}

	local ok = false
	local err = nil
	if common.is_windows() then
		result.platform = "windows"
		ok, err = _windows(opt, result)
	elseif common.has_systemctl() then
		result.platform = "linux"
		ok, err = _linux(opt, result)
		if not ok and type(err) == "string" then
			result.platform = "linux (systemd)"
		end
	elseif common.has_initd() then
		result.platform = "embedded"
		ok, err = _initd(opt, result)
	else
		result.platform = "unsupported"
		err = "no systemd / init.d / Task Scheduler; persistent enable unsupported;"
			.. " foreground: alua pkg run alua_web serve @web.json"
	end

	if ok then
		result.ok = true
		if want_json then
			fmt.print_json(result)
		else
			_print_text(result)
		end

		return true, codes.OK
	end

	result.ok = false
	result.message = tostring(err or "fail")
	if want_json then
		fmt.print_json(result)
	else
		io.stderr:write("alua setup web: " .. result.message .. "\n")
	end

	if result.platform == "unsupported" then
		return false, codes.cli.NOT_IMPLEMENTED
	end

	return false, codes.cli.TOOL_FAILED
end


return M

